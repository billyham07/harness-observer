// Package pricing turns an observed model name into published per-token rates
// so the read side can express normalized token evidence as an API-equivalent
// dollar estimate.
//
// Three boundaries make this safe to trust:
//
//   - It is an estimate, never a bill. Subscription and OAuth usage is not
//     metered spend, so nothing here is allowed to be called actual cost. The
//     source-reported cost a session file already contains stays separate
//     evidence and is never synthesized from this catalog.
//   - An unresolved model is unpriced, not free. Every bucket of tokens whose
//     rate is unknown is counted as unpriced so coverage can be reported
//     token-weighted instead of collapsing into a confident $0.
//   - Resolution is conservative and explainable. Every match records which
//     rule fired and which catalog key and version produced the rate. There is
//     no fuzzy or prefix matching that could price a future model variant at an
//     older variant's rate.
//
// The bundled snapshot makes the whole package work offline; the remote
// refresh is best effort and downloads only a public pricing catalog. No model,
// session or usage data ever leaves the machine.
package pricing

import (
	"crypto/sha256"
	_ "embed"
	"encoding/json"
	"fmt"
	"math"
	"sort"
	"strings"
	"time"
)

// catalog.json is a filtered snapshot of LiteLLM's public model pricing table,
// regenerated by scripts/genpricing. Only the four rate fields, the provider
// and chat-shaped models are kept, which is what makes a 1.8 MB upstream file a
// ~190 KB embedded one.
//
//go:embed catalog.json
var bundledSnapshot []byte

// Where a catalog came from. This travels with every match so a number on the
// dashboard can always be traced back to the table that produced it.
const (
	SourceBundled = "bundled"
	SourceCached  = "cached"
	SourceRemote  = "remote"
)

// maxSaneRate rejects a catalog entry whose units are obviously wrong. One US
// dollar per token is $1,000,000 per million tokens; no published rate is
// within three orders of magnitude of it, so a value this large means the
// upstream row is per-million or corrupt.
const maxSaneRate = 1.0

// Rates are per-token USD prices. A nil field means the catalog publishes no
// rate for that bucket, which is different from a published zero: local and
// free-tier models legitimately cost 0.
type Rates struct {
	Input      *float64 `json:"input,omitempty"`
	Output     *float64 `json:"output,omitempty"`
	CacheRead  *float64 `json:"cache_read,omitempty"`
	CacheWrite *float64 `json:"cache_write,omitempty"`
}

// Empty reports whether the catalog published no usable rate at all.
func (r Rates) Empty() bool {
	return r.Input == nil && r.Output == nil && r.CacheRead == nil && r.CacheWrite == nil
}

func (r Rates) equal(other Rates) bool {
	return sameRate(r.Input, other.Input) && sameRate(r.Output, other.Output) &&
		sameRate(r.CacheRead, other.CacheRead) && sameRate(r.CacheWrite, other.CacheWrite)
}

func sameRate(a, b *float64) bool {
	switch {
	case a == nil && b == nil:
		return true
	case a == nil || b == nil:
		return false
	default:
		return *a == *b
	}
}

func rate(v float64) *float64 { return &v }

// validRate keeps a rate only if it is a finite, non-negative, plausible price.
// A negative or NaN rate is rejected rather than clamped: silently turning bad
// data into 0 is exactly the "unknown became free" failure this package exists
// to avoid.
func validRate(v float64) (*float64, bool) {
	if math.IsNaN(v) || math.IsInf(v, 0) || v < 0 || v > maxSaneRate {
		return nil, false
	}
	return &v, true
}

// Entry is one catalog row.
type Entry struct {
	Provider string `json:"provider,omitempty"`
	Rates    Rates  `json:"rates"`
}

// Catalog is an immutable set of model rates plus the provenance needed to
// explain them.
type Catalog struct {
	Source    string
	Version   string // short, human quotable digest of the priced content
	Digest    string // full digest, so a cache round trip does not lose it
	FetchedAt time.Time
	Models    map[string]Entry

	// lower resolves a case-insensitive exact match; suffix resolves a bare
	// model name against provider-prefixed catalog keys. Both are built once so
	// resolution never scans the table.
	lower  map[string]string
	suffix map[string][]string
}

// Len is the number of priced models.
func (c *Catalog) Len() int {
	if c == nil {
		return 0
	}
	return len(c.Models)
}

func newCatalog(source, digest string, fetchedAt time.Time, models map[string]Entry) *Catalog {
	c := &Catalog{
		Source:    source,
		Version:   shortDigest(digest),
		Digest:    digest,
		FetchedAt: fetchedAt,
		Models:    models,
		lower:     make(map[string]string, len(models)),
		suffix:    make(map[string][]string),
	}
	keys := make([]string, 0, len(models))
	for k := range models {
		keys = append(keys, k)
	}
	// Sorted so a duplicate case-folding or suffix collision resolves to the
	// same key on every run instead of depending on map iteration order.
	sort.Strings(keys)
	for _, k := range keys {
		lk := strings.ToLower(k)
		if _, exists := c.lower[lk]; !exists {
			c.lower[lk] = k
		}
		if i := strings.LastIndex(k, "/"); i >= 0 && i+1 < len(k) {
			tail := k[i+1:]
			c.suffix[tail] = append(c.suffix[tail], k)
		}
	}
	return c
}

// snapshot is the compact on-disk form: the bundled catalog and the refresh
// cache are byte-identical in shape, so both load through one parser.
type snapshot struct {
	Source      string                   `json:"source"`
	URL         string                   `json:"url,omitempty"`
	GeneratedAt string                   `json:"generated_at,omitempty"`
	FetchedAt   string                   `json:"fetched_at,omitempty"`
	Upstream    string                   `json:"upstream_sha256,omitempty"`
	Models      map[string]snapshotEntry `json:"models"`
}

type snapshotEntry struct {
	Provider   string   `json:"p,omitempty"`
	Input      *float64 `json:"i,omitempty"`
	Output     *float64 `json:"o,omitempty"`
	CacheRead  *float64 `json:"r,omitempty"`
	CacheWrite *float64 `json:"w,omitempty"`
}

func parseSnapshot(data []byte, source string) (*Catalog, error) {
	var snap snapshot
	if err := json.Unmarshal(data, &snap); err != nil {
		return nil, fmt.Errorf("pricing snapshot: %w", err)
	}
	models := make(map[string]Entry, len(snap.Models))
	for name, e := range snap.Models {
		entry := Entry{Provider: e.Provider}
		entry.Rates.Input = keepRate(e.Input)
		entry.Rates.Output = keepRate(e.Output)
		entry.Rates.CacheRead = keepRate(e.CacheRead)
		entry.Rates.CacheWrite = keepRate(e.CacheWrite)
		if entry.Rates.Empty() {
			continue
		}
		models[name] = entry
	}
	if len(models) == 0 {
		return nil, fmt.Errorf("pricing snapshot: no usable model rates")
	}
	fetched := time.Time{}
	for _, candidate := range []string{snap.FetchedAt, snap.GeneratedAt} {
		if candidate == "" {
			continue
		}
		for _, layout := range []string{time.RFC3339, "2006-01-02"} {
			if t, err := time.Parse(layout, candidate); err == nil {
				fetched = t
				break
			}
		}
		if !fetched.IsZero() {
			break
		}
	}
	return newCatalog(source, snapshotDigest(snap, data), fetched, models), nil
}

// snapshotDigest prefers the upstream digest, because two snapshots generated
// on different days from the same upstream file describe the same prices.
func snapshotDigest(snap snapshot, data []byte) string {
	if snap.Upstream != "" {
		return snap.Upstream
	}
	sum := sha256.Sum256(data)
	return fmt.Sprintf("%x", sum)
}

func shortDigest(hex string) string {
	if len(hex) > 12 {
		return hex[:12]
	}
	return hex
}

func keepRate(v *float64) *float64 {
	if v == nil {
		return nil
	}
	kept, ok := validRate(*v)
	if !ok {
		return nil
	}
	return kept
}

// upstreamEntry is the subset of LiteLLM's model_prices_and_context_window.json
// this package understands. Every other field in that file describes context
// windows, modalities or capabilities and has no bearing on a price.
type upstreamEntry struct {
	Provider   string   `json:"litellm_provider"`
	Mode       string   `json:"mode"`
	Input      *float64 `json:"input_cost_per_token"`
	Output     *float64 `json:"output_cost_per_token"`
	CacheRead  *float64 `json:"cache_read_input_token_cost"`
	CacheWrite *float64 `json:"cache_creation_input_token_cost"`
}

// ParseUpstream reads the public LiteLLM pricing table. Rows that are not chat
// shaped, carry no usable rate, or carry an implausible one are dropped rather
// than imported and later mistaken for evidence.
func ParseUpstream(data []byte, source, digest string, fetchedAt time.Time) (*Catalog, error) {
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("pricing catalog: %w", err)
	}
	models := make(map[string]Entry, len(raw))
	for name, blob := range raw {
		if name == "sample_spec" {
			continue
		}
		var e upstreamEntry
		if err := json.Unmarshal(blob, &e); err != nil {
			// One malformed row must not discard the rest of the table.
			continue
		}
		switch e.Mode {
		case "", "chat", "responses", "completion":
		default:
			continue
		}
		entry := Entry{Provider: e.Provider}
		entry.Rates.Input = keepRate(e.Input)
		entry.Rates.Output = keepRate(e.Output)
		entry.Rates.CacheRead = keepRate(e.CacheRead)
		entry.Rates.CacheWrite = keepRate(e.CacheWrite)
		if entry.Rates.Input == nil && entry.Rates.Output == nil {
			// Cache rates alone cannot price a turn and would report misleading
			// coverage, so such a row is not a usable catalog entry.
			continue
		}
		models[name] = entry
	}
	if len(models) < minUsableModels {
		return nil, fmt.Errorf("pricing catalog: only %d usable models, refusing to replace the current catalog", len(models))
	}
	return newCatalog(source, digest, fetchedAt, models), nil
}

// minUsableModels is the sanity floor for a downloaded catalog. A truncated
// response, an HTML error page or a partially written file will not clear it,
// which is what keeps a bad refresh from silently shrinking coverage.
const minUsableModels = 100

// Bundled returns the embedded offline catalog.
func Bundled() (*Catalog, error) { return parseSnapshot(bundledSnapshot, SourceBundled) }

// encodeSnapshot renders a catalog in the compact on-disk form used by the
// refresh cache.
func encodeSnapshot(c *Catalog, url string, fetchedAt time.Time) ([]byte, error) {
	snap := snapshot{
		Source:    c.Source,
		URL:       url,
		FetchedAt: fetchedAt.UTC().Format(time.RFC3339),
		Upstream:  c.Digest,
		Models:    make(map[string]snapshotEntry, len(c.Models)),
	}
	for name, e := range c.Models {
		snap.Models[name] = snapshotEntry{
			Provider:   e.Provider,
			Input:      e.Rates.Input,
			Output:     e.Rates.Output,
			CacheRead:  e.Rates.CacheRead,
			CacheWrite: e.Rates.CacheWrite,
		}
	}
	return json.Marshal(snap)
}
